function question(query: string, prompt: string): SuggestionContent {
  return { query, prompt, category: 'project-qa', icon: '/assets/figma/template-discovery/project-qa.svg' };
}

function development(query: string, prompt: string): SuggestionContent {
  return { query, prompt, category: 'project-development', icon: developmentNode.icon };
}

