function getDeviceQueries(project: string): readonly SuggestionContent[] {
  const queries = deviceProjectQueries[project];
  if (!queries) return projectQueries[project] ?? folderFallback;
  return queries.map((query, index) => index < 2
    ? question(query, `请${query}。先阅读当前目录中的说明文档、配置和相关实现，结合一个典型使用场景追踪执行过程，区分已确认的问题与待验证假设。请提供对应的文件位置和证据，整理关键结论、影响范围以及下一步排查或改进建议。`)
    : development(query, `请${query}。先结合当前目录的代码与项目约定明确目标和验收标准，定位相关模块并制定实现步骤，再完成必要的修改。保留现有功能和兼容性，覆盖异常与边界场景，运行相关测试和构建，最后汇总改动、验证结果及仍需确认的事项。`));
}

