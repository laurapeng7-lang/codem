export function getSuggestedQueries(context?: SuggestionContext): SuggestedQuery[] {
  if (!context) return landingSuggestions;
  const queries = context.kind === 'folder'
    ? context.device ? getDeviceQueries(context.name) : projectQueries[context.id] ?? folderFallback
    : sourceQueries;
  return [...queries, developmentNode].map((suggestion, index) => ({
    ...suggestion,
    id: `${context.id}:${index}`,
    prompt: `${context.device ? `当前设备：「${context.device}」。\n当前目录：「${context.name}」。` : `当前${context.kind === 'folder' ? '项目' : '工作项'}：「${context.name}」。`}\n\n${suggestion.prompt}`,
  }));
}
